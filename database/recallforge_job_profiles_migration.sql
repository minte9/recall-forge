-- RecallForge: predefined Job Profiles MVP
-- PostgreSQL 16
-- Run against the RecallForge database as a schema owner.
-- Back up production before applying. Test on local/test first.
-- Assumptions:
--   public.user_accounts(id) exists and id is BIGINT-compatible.
--   Template account has id = 1.
--   public.category_order(id, environment, category) exists.
--   Mappings are based on the confirmed 23 category names (October 2026),
--   plus API/GraphQL and API/MCP, which this migration adds to category_order.

BEGIN;

-- 1. Predefined profiles owned by template user (shared read-only by application logic).
CREATE TABLE IF NOT EXISTS job_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_accounts(id),
    name VARCHAR(150) NOT NULL,
    description TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_job_profiles_user_name UNIQUE (user_id, name)
);

CREATE INDEX IF NOT EXISTS idx_job_profiles_user_enabled
    ON job_profiles (user_id, enabled);

-- 2. Mapping between profiles and category identifiers.
-- category_id references category_order; FK added below for existing installations.
CREATE TABLE IF NOT EXISTS job_profile_categories (
    profile_id BIGINT NOT NULL REFERENCES job_profiles(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL,
    PRIMARY KEY (profile_id, category_id)
);

CREATE INDEX IF NOT EXISTS idx_job_profile_categories_category
    ON job_profile_categories (category_id);

-- 3. Remember each user's default profile between visits and devices.
-- NULL means 'All Categories'. ON DELETE SET NULL resets the preference.
ALTER TABLE user_accounts
    ADD COLUMN IF NOT EXISTS active_job_profile_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_user_accounts_active_job_profile'
          AND conrelid = 'user_accounts'::regclass
    ) THEN
        ALTER TABLE user_accounts
            ADD CONSTRAINT fk_user_accounts_active_job_profile
            FOREIGN KEY (active_job_profile_id)
            REFERENCES job_profiles(id) ON DELETE SET NULL;
    END IF;
END $$;

-- 4. Seed template profiles (repeatable: existing names will not be duplicated).
-- Fail explicitly if the template account is missing.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM user_accounts WHERE id = 1) THEN
        RAISE EXCEPTION 'Template user id=1 is missing. Migration aborted.';
    END IF;
END $$;

INSERT INTO job_profiles (user_id, name, description, enabled)
VALUES
    (1, 'Java Backend Developer', 'Java, Spring Boot, REST, SQL, PostgreSQL, Docker, Git', TRUE),
    (1, 'Java Full-Stack Developer', 'Java, Spring Boot, REST, TypeScript, Angular, SQL, Git', TRUE),
    (1, 'Microservices Engineer', 'Java, Spring Boot, REST, Kafka, RabbitMQ, Docker, SQL', TRUE),
    (1, 'AI Integration Engineer', 'Java, Spring AI, MCP, REST, Python, LLM Integration', TRUE)
ON CONFLICT (user_id, name) DO NOTHING;

-- 5. Link profile categories to the actual category_order table.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_job_profile_category'
          AND conrelid = 'job_profile_categories'::regclass
    ) THEN
        ALTER TABLE job_profile_categories
            ADD CONSTRAINT fk_job_profile_category
            FOREIGN KEY (category_id) REFERENCES category_order(id);
    END IF;
END $$;

-- 6. Ensure API categories used by profiles exist in category_order
-- (GraphQL and MCP have starter-pack content but no category_order row).
INSERT INTO category_order (environment, category, display_order)
VALUES
    ('API', 'GraphQL', 2),
    ('API', 'MCP', 3)
ON CONFLICT (environment, category) DO NOTHING;

-- 7. Insert mappings by stable (environment, category), not numeric IDs.
-- Re-running this block does not create duplicates.
WITH desired(profile_name, environment, category) AS (
    VALUES
      ('Java Backend Developer', 'JVM', 'Java'),
      ('Java Backend Developer', 'JVM', 'Spring'),
      ('Java Backend Developer', 'API', 'REST'),
      ('Java Backend Developer', 'API', 'GraphQL'),
      ('Java Backend Developer', 'DB', 'SQL'),
      ('Java Backend Developer', 'DB', 'PostgreSQL'),
      ('Java Backend Developer', 'DevOps', 'Docker'),
      ('Java Backend Developer', 'DevOps', 'Git'),
      ('Java Full-Stack Developer', 'JVM', 'Java'),
      ('Java Full-Stack Developer', 'JVM', 'Spring'),
      ('Java Full-Stack Developer', 'API', 'REST'),
      ('Java Full-Stack Developer', 'API', 'GraphQL'),
      ('Java Full-Stack Developer', 'JS', 'TypeScript'),
      ('Java Full-Stack Developer', 'JS', 'Javascript'),
      ('Java Full-Stack Developer', 'DB', 'SQL'),
      ('Java Full-Stack Developer', 'DB', 'PostgreSQL'),
      ('Java Full-Stack Developer', 'DevOps', 'Docker'),
