INSERT INTO job_profile_categories (profile_id, category_id)
SELECT jp.id, co.id
FROM desired d
JOIN job_profiles jp ON jp.user_id = 1 AND jp.name = d.profile_name
JOIN category_order co ON co.environment = d.environment
                      AND co.category = d.category
ON CONFLICT (profile_id, category_id) DO NOTHING;

-- Validate mappings without arithmetic exceptions or planner constant folding.
DO $$
DECLARE
    actual_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO actual_count
    FROM job_profile_categories jpc
    JOIN job_profiles jp ON jp.id = jpc.profile_id
    WHERE jp.user_id = 1
      AND jp.name IN (
        'Java Backend Developer', 'Java Full-Stack Developer',
        'Microservices Engineer', 'AI Integration Engineer'
      );
    IF actual_count <> 33 THEN
        RAISE EXCEPTION 'Expected 33 profile/category mappings; found %', actual_count;
    END IF;
END $$;

COMMIT;

-- Verification: expected counts are 8, 10, 8, 7.
SELECT jp.name, COUNT(jpc.category_id) AS category_count
FROM job_profiles jp
LEFT JOIN job_profile_categories jpc ON jpc.profile_id = jp.id
WHERE jp.user_id = 1
GROUP BY jp.id, jp.name
ORDER BY jp.id;

SELECT jp.name, co.environment, co.category
FROM job_profile_categories jpc
JOIN job_profiles jp ON jp.id = jpc.profile_id
JOIN category_order co ON co.id = jpc.category_id
WHERE jp.user_id = 1
ORDER BY jp.id, co.environment, co.category;

